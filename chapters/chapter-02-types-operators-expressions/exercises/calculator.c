#include <stdio.h>

int main() {
    // 程序介绍
    printf("🧮 费曼教授的交互式计算器\n");
    printf("============================\n");
    printf("支持: +, -, *, /, %%, >, <, >=, <=, ==, !=, &&, ||, !\n");
    printf("输入 'q' 退出程序\n\n");

    double num1, num2;
    char operator;
    int continue_calc = 1;

    while (continue_calc) {
        // 获取用户输入
        printf("请输入表达式 (例如: 5 + 3): ");

        // 读取第一个数字
        if (scanf("%lf", &num1) != 1) {
            // 检查是否要退出
            char quit_check;
            scanf(" %c", &quit_check);
            if (quit_check == 'q' || quit_check == 'Q') {
                printf("👋 再见！感谢使用费曼计算器！\n");
                break;
            }
            printf("❌ 输入错误，请重新输入！\n");
            // 清空输入缓冲区
            while (getchar() != '\n');
            continue;
        }

        // 读取运算符
        scanf(" %c", &operator);

        // 读取第二个数字
        if (scanf("%lf", &num2) != 1) {
            printf("❌ 第二个数字输入错误！\n");
            while (getchar() != '\n');
            continue;
        }

        // 根据运算符进行计算
        printf("📊 计算结果: ");

        switch (operator) {
            case '+':
                printf("%.2f + %.2f = %.2f\n", num1, num2, num1 + num2);
                break;

            case '-':
                printf("%.2f - %.2f = %.2f\n", num1, num2, num1 - num2);
                break;

            case '*':
                printf("%.2f * %.2f = %.2f\n", num1, num2, num1 * num2);
                break;

            case '/':
                if (num2 != 0) {
                    printf("%.2f / %.2f = %.6f\n", num1, num2, num1 / num2);
                } else {
                    printf("❌ 错误：除数不能为零！\n");
                }
                break;

            case '%':
                printf("%d %% %d = %d\n", (int)num1, (int)num2, (int)num1 % (int)num2);
                printf("💡 注意：%% 运算符只适用于整数！\n");
                break;

            case '>':
                printf("%.2f > %.2f 是 %s\n", num1, num2,
                       (num1 > num2) ? "真(1)" : "假(0)");
                break;

            case '<':
                printf("%.2f < %.2f 是 %s\n", num1, num2,
                       (num1 < num2) ? "真(1)" : "假(0)");
                break;

            case '=':  // 支持 == 操作
                {
                    char next_char;
                    scanf(" %c", &next_char);
                    if (next_char == '=') {
                        printf("%.2f == %.2f 是 %s\n", num1, num2,
                               (num1 == num2) ? "真(1)" : "假(0)");
                    } else {
                        printf("❌ 不支持的操作符！\n");
                    }
                }
                break;

            case '!':  // 支持 != 操作
                {
                    char next_char;
                    scanf(" %c", &next_char);
                    if (next_char == '=') {
                        printf("%.2f != %.2f 是 %s\n", num1, num2,
                               (num1 != num2) ? "真(1)" : "假(0)");
                    } else {
                        printf("❌ 不支持的操作符！\n");
                    }
                }
                break;

            default:
                printf("❌ 不支持的运算符: %c\n", operator);
                printf("💡 支持的运算符: +, -, *, /, %%, >, <, >=, <=, ==, !=\n");
                break;
        }

        printf("\n");  // 空行分隔

        // 清空输入缓冲区
        while (getchar() != '\n');
    }

    return 0;
}

